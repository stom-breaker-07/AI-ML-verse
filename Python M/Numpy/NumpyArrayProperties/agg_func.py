# Aggrigation function on Array

import numpy as np

np_arr=np.array([[1,2],[3,4],[5,6]])

print("Sum of all element in array",np_arr.sum())
print("Mean of all element in array",np_arr.mean())
print("Standard deviation of all element in array",np_arr.std())
print("Minimum element in array",np_arr.min())
print("Maximum element in array",np_arr.max())
print("Varience",np_arr.var())