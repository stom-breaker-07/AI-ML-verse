# Mathematical Operations on NumPy Arrays

import numpy as np

np_arr=np.array([[1,2],[3,4]])
print(np_arr + 2) # add 2 to each element
print(np_arr - 1) # subtract 1 from each element
print(np_arr * 3) # multiply each element by 3
print(np_arr / 2) # divide each element by 2
print(np_arr ** 2) # square each element
print(np_arr % 2) # modulus of each element by 2